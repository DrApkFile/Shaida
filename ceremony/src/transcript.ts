// Renders ceremony/TRANSCRIPT.md from record.json. Generated after every step; never edit by hand.
import type { CeremonyRecord, Contribution } from "./record.js";

const short = (hex: string) => `${hex.slice(0, 16)}…`;
const block = (hash: string) => hash.match(/.{1,32}/g)!.join("\n");

function contributionRows(cs: readonly Contribution[]): string[] {
  return cs.map(
    (c) => `| ${c.n} | ${c.name || "(no name)"} | ${c.beacon ? `beacon ${c.beacon.value}, 2^${c.beacon.iterationsExp}` : "contribution"} | \`${short(c.hash)}\` |`,
  );
}

export function renderTranscript(r: CeremonyRecord): string {
  const out: string[] = [];
  out.push("# Phase-2 ceremony transcript: income circuit (Groth16)", "");
  if (r.dryRun) out.push("> **DRY RUN.** A rehearsal with test entropy. Not the ceremony; never use these keys.", "");
  out.push("Generated by `ceremony/*.ts` from `record.json` after every step. Procedure: `briefing/CEREMONY.md`.", "");
  out.push("## Inputs", "");
  out.push("| Item | Value |", "|---|---|");
  out.push(`| snarkjs | ${r.snarkjs} |`);
  out.push(`| r1cs | \`${r.circuit.r1cs}\` sha256 \`${r.circuit.r1csSha256}\` |`);
  out.push(`| ptau | ${r.ptau.name} blake2b \`${r.ptau.blake2b}\` |`);
  out.push(`| setup zkey (no contribution yet) | \`${r.setup.zkey.path}\` sha256 \`${r.setup.zkey.sha256}\` (${r.setup.at}) |`, "");

  out.push("## Verified zkeys", "");
  if (r.verified.length === 0) out.push("None yet.", "");
  for (const v of r.verified) {
    out.push(`### \`${v.zkey.path}\``, "");
    out.push(`sha256 \`${v.zkey.sha256}\`, verified ${v.at} against the r1cs and ptau above (log: \`${v.log}\`).`, "");
    out.push("| # | Name in the zkey | Kind | Contribution hash |", "|---|---|---|---|", ...contributionRows(v.contributions), "");
    for (const c of v.contributions) out.push(`Contribution #${c.n} hash:`, "```", block(c.hash), "```");
    out.push("");
  }

  out.push("## Beacon", "");
  const a = r.beaconAnnouncement;
  if (a === null) out.push("Not announced yet.", "");
  else {
    out.push(
      `Announced ${a.at}: block **${a.blockNumber}** on chain ${a.chainId}, for zkey sha256 \`${a.forZkey.sha256}\`. ` +
        `Head was ${a.headAtAnnouncement} (timestamp ${a.headTimestamp}); at ${a.blockSeconds} s per block the block is expected near unix ${a.expectedTimestamp}.`,
      "",
    );
  }
  const b = r.beacon;
  if (b !== null) {
    out.push(`Applied ${b.at}: block ${b.blockNumber} hash \`${b.blockHash}\` (timestamp ${b.blockTimestamp}), 2^${b.iterationsExp} iterations.`);
    out.push(
      b.announcementCommit
        ? `Announced in commit \`${b.announcementCommit.sha}\` (committed at unix ${b.announcementCommit.committedAt}, before the block).`
        : "Dry run: no announcement commit.",
    );
    out.push(`Output \`${b.out.path}\` sha256 \`${b.out.sha256}\`, contribution hash \`${short(b.contributionHash)}\`.`, "");
  }

  out.push("## Final key", "");
  const f = r.final;
  if (f === null) out.push("Not finalized yet.", "");
  else {
    out.push("| File | sha256 |", "|---|---|");
    out.push(`| \`${f.zkey.path}\` | \`${f.zkey.sha256}\` |`, `| \`${f.vkey.path}\` | \`${f.vkey.sha256}\` |`, `| \`${f.verifier.path}\` | \`${f.verifier.sha256}\` |`, "");
    out.push(
      `Verifier runtime ${f.verifierRuntimeBytes} bytes, Shanghai check ${f.shanghaiCheck}. Sample proof with the final key: verified, tampered threshold refused (prove ${(f.sampleProof.proveMs / 1000).toFixed(2)} s). Finalized ${f.at}.`,
      "",
    );
  }
  return `${out.join("\n")}\n`;
}
