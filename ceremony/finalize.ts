// Last step, after the beacon output is verified: exports the verification key and the Solidity verifier, compiles
// the verifier alone (solc 0.8.24, Shanghai) and runs tools/check-shanghai.mjs on it, proves one sample witness with
// the final key, and writes every hash to record.json / TRANSCRIPT.md.
// Real run: vkey → packages/shaida-proofs/keys/income_final_vkey.json, verifier →
// contracts/src/generated/IncomeGroth16Verifier.sol (contract IncomeGroth16Verifier). Dry run: CEREMONY_DIR/out/.
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { ceremonyPaths, MIN_CONTRIBUTIONS, REPO, requireFile, WASM } from "./src/config.js";
import { recordedPath, sha256File } from "./src/files.js";
import { main } from "./src/main.js";
import { humanContributions, lastVerified, readRecord, writeRecord } from "./src/record.js";
import { sampleProofCheck } from "./src/sample.js";
import { assertSnarkjsVersion, exportSolidityVerifier, exportVerificationKey } from "./src/snarkjs.js";

function run(cmd: string, args: string[], what: string): string {
  const r = spawnSync(cmd, args, { cwd: REPO, encoding: "utf8" });
  if (r.status !== 0) throw new Error(`${what} failed (exit ${r.status}):\n${r.stdout}${r.stderr}`);
  return r.stdout;
}

main("finalize", async () => {
  const paths = ceremonyPaths();
  assertSnarkjsVersion();
  const record = readRecord(paths);
  if (record.final !== null) throw new Error("already finalized; nothing was changed.");
  const b = record.beacon;
  if (b === null) throw new Error("no beacon applied yet.");
  const v = lastVerified(record);
  if (v === null || v.zkey.sha256 !== b.out.sha256) throw new Error("verify the beacon output first.");
  const beaconEntry = v.contributions.at(-1);
  if (beaconEntry?.beacon?.value !== b.blockHash.slice(2) || beaconEntry.beacon.iterationsExp !== b.iterationsExp) {
    throw new Error("the verified zkey's last contribution is not the recorded beacon.");
  }
  if (humanContributions(v).length < MIN_CONTRIBUTIONS) throw new Error(`fewer than ${MIN_CONTRIBUTIONS} contributions before the beacon.`);
  const zkey = requireFile(resolve(REPO, b.out.path), "final zkey");
  if ((await sha256File(zkey)) !== b.out.sha256) throw new Error(`${zkey} changed since it was verified.`);

  // 1. verification key
  const vkey = await exportVerificationKey(zkey);
  mkdirSync(dirname(paths.vkeyOut), { recursive: true });
  writeFileSync(paths.vkeyOut, `${JSON.stringify(vkey, null, 1)}\n`);

  // 2. Solidity verifier: snarkjs template, contract renamed, one provenance line under its GPL-3.0 header
  const raw = join(paths.work, "verifier.raw.sol");
  exportSolidityVerifier(zkey, raw);
  const source = readFileSync(raw, "utf8");
  if (!source.includes("contract Groth16Verifier")) throw new Error("unexpected snarkjs verifier template (no contract Groth16Verifier).");
  const provenance = `// Generated by ceremony/finalize.ts (snarkjs ${record.snarkjs} template) from income_final.zkey sha256 ${b.out.sha256}.\n// Do not edit: regenerate from the ceremony. Transcript: ceremony/TRANSCRIPT.md.\n`;
  const renamed = source.replace("contract Groth16Verifier", "contract IncomeGroth16Verifier").replace(/(pragma solidity[^\n]*\n)/, `$1\n${provenance}`);
  mkdirSync(dirname(paths.verifierOut), { recursive: true });
  writeFileSync(paths.verifierOut, renamed);
  rmSync(raw);

  // 3. compile alone (Shanghai) and check opcodes
  rmSync(paths.forge, { recursive: true, force: true });
  mkdirSync(join(paths.forge, "src"), { recursive: true });
  copyFileSync(paths.verifierOut, join(paths.forge, "src/IncomeGroth16Verifier.sol"));
  writeFileSync(join(paths.forge, "foundry.toml"), '[profile.default]\nsrc = "src"\nout = "out"\nsolc_version = "0.8.24"\nevm_version = "shanghai"\noptimizer = true\noptimizer_runs = 200\n');
  const sizes = run("forge", ["build", "--root", paths.forge, "--sizes"], "forge build of the verifier");
  run(process.execPath, ["tools/check-shanghai.mjs", join(paths.forge, "out")], "Shanghai check");
  const runtime = sizes.match(/IncomeGroth16Verifier\s*\|\s*([\d,]+)/)?.[1];
  if (runtime === undefined) throw new Error(`no runtime size for IncomeGroth16Verifier in forge output:\n${sizes}`);
  console.log(`✓ verifier compiled (${runtime} bytes runtime), Shanghai check passed`);

  // 4. sample proof with the final key
  const sample = await sampleProofCheck(requireFile(WASM, "income.wasm (run `make build`)"), zkey, vkey);
  if (!sample.verified || !sample.tamperedRefused) throw new Error(`sample proof check failed: ${JSON.stringify(sample)}`);
  console.log(`✓ sample proof verified with the exported vkey; tampered threshold refused (prove ${sample.proveMs} ms)`);

  record.final = {
    zkey: b.out,
    vkey: { path: recordedPath(paths.vkeyOut), sha256: await sha256File(paths.vkeyOut) },
    verifier: { path: recordedPath(paths.verifierOut), sha256: await sha256File(paths.verifierOut) },
    verifierRuntimeBytes: Number(runtime.replace(/,/g, "")),
    shanghaiCheck: "pass",
    sampleProof: { verified: true, tamperedRefused: true, proveMs: sample.proveMs },
    at: new Date().toISOString(),
  };
  writeRecord(paths, record);
  console.log(`✓ finalized. zkey ${b.out.sha256}\n  vkey ${record.final.vkey.path} ${record.final.vkey.sha256}\n  verifier ${record.final.verifier.path} ${record.final.verifier.sha256}`);
});
