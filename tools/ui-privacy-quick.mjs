#!/usr/bin/env node
// D32 quick fixes in headless Chromium at 390 px (CLAUDE.md) on `make fork`: the landing page's pitch, and /v with a
// fixture link: "Record check" stays disabled until the warning's box is ticked (F3), and the expiry is shown in the
// viewer's time zone (F8). Nothing is sent: the record button is checked, never clicked. Writes evidence/ui-privacy-quick/.
// Usage: node tools/ui-privacy-quick.mjs [--base http://localhost:3100] [--chromium /usr/bin/chromium]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { withChromium } from "./ui-cdp.mjs";

const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i >= 0 ? process.argv[i + 1] : d; };
const BASE = arg("base", "http://localhost:3100");
const REPO = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(REPO, "evidence/ui-privacy-quick");
const log = [];
const note = (s) => { log.push(`- ${s}`); console.log(s); };
const link = JSON.parse(readFileSync(join(REPO, "tools/privacy/fixtures/fork-truth-fixes.json"), "utf8")).links.find((l) => l.name === "ada").from.url;
mkdirSync(OUT, { recursive: true });

await withChromium({ chromium: arg("chromium", "/usr/bin/chromium"), port: 9341, base: BASE, out: OUT, note }, async (_c, page) => {
  const p = await page("reader");
  await p.send("Emulation.setTimezoneOverride", { timezoneId: "Africa/Lagos" }); // UTC+1, as the bot link's maker
  await p.goto("/");
  const lede = await p.eval(`document.querySelector(".lede")?.innerText ?? ""`);
  if (!lede.startsWith("Who got paid and how much stays private; which registered payer paid is public by design")) throw new Error(`landing lede: ${lede}`);
  note(`landing: h1 "${await p.eval(`document.querySelector("h1").innerText`)}"; lede "${lede}"`);
  await p.shot("390-01-landing");

  await p.goto(link);
  await p.type("input[name=reader]", "Landlord Bola");
  await p.click("Verify");
  await p.until(`document.body.innerText.includes("Link expires")`, 120_000, "verdict");
  const expires = await p.eval(`[...document.querySelectorAll("dt")].find((d) => d.innerText.includes("Link expires"))?.nextElementSibling?.innerText ?? ""`);
  note(`/v verdict: Link expires "${expires}" (viewer in Africa/Lagos, UTC+1; the link ends 23:59:59 UTC)`);
  const record = `[...document.querySelectorAll("button")].find((b) => b.innerText.startsWith("Record check"))`;
  await p.until(record, 60_000, "Record check button");
  const before = await p.eval(`${record}.disabled`);
  const warning = await p.eval(`document.querySelector(".public-record")?.innerText ?? ""`);
  if (!before || !warning.includes("public and permanent")) throw new Error(`record before consent: disabled ${before}, warning "${warning}"`);
  note(`/v: before the box is ticked "Record check" disabled = ${before}; warning shown: "${warning.split("\n")[0]}"`);
  await p.shot("390-02-record-consent");
  await p.eval(`document.querySelector('.public-record input[type=checkbox]').click()`);
  const after = await p.eval(`${record}.disabled`);
  note(`/v: after ticking, "Record check" disabled = ${after} (the demo signer needs a fork wallet; it was not clicked, nothing sent)`);
  await p.shot("390-03-record-consented");
});

writeFileSync(join(OUT, "report.md"), `# D32 quick fixes at 390 px (fork)\n\nGenerated by \`node tools/ui-privacy-quick.mjs --base ${BASE}\` (headless Chromium), ${new Date().toISOString()}. Demo personas. Nothing was sent.\n\n${log.join("\n")}\n`);
process.exit(0);
