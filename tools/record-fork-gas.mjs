#!/usr/bin/env node
// Runs the step-1 exit-check fork test and writes its gas figures to evidence/fork-gas.md.
// Every number in that file comes from this run's output; a failed run writes nothing and exits 1.
// Usage: node tools/record-fork-gas.mjs [--rpc https://rpc-test.qday.info]
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const ROOT = resolve(dirname(new URL(import.meta.url).pathname), "..");
const rpcFlag = process.argv.indexOf("--rpc");
const RPC = rpcFlag >= 0 ? process.argv[rpcFlag + 1] : "https://rpc-test.qday.info";
const TEST = "test/fork/ExitCheckFork.t.sol";
const args = ["test", "--isolate", "--match-path", TEST, "--fork-url", RPC, "-vv"];

function fail(message) {
  console.error(`✗ record-fork-gas: ${message}`);
  process.exit(1);
}

const git = (a) => execFileSync("git", a, { cwd: ROOT, encoding: "utf8" }).trim();
const forkBlock = (() => {
  const out = spawnSync("cast", ["block-number", "--rpc-url", RPC], { encoding: "utf8" });
  if (out.status !== 0) fail(`cast block-number: ${out.stderr.trim()}`);
  return out.stdout.trim();
})();

// Aevum's own block gas limit, read from the live chain's latest block (not the fork's anvil default).
const liveBlock = (() => {
  const out = spawnSync("cast", ["rpc", "eth_getBlockByNumber", "latest", "false", "--rpc-url", RPC], {
    encoding: "utf8",
  });
  if (out.status !== 0) fail(`eth_getBlockByNumber: ${out.stderr.trim()}`);
  const block = JSON.parse(out.stdout);
  if (typeof block.gasLimit !== "string" || typeof block.number !== "string") fail("latest block has no gasLimit");
  return { number: BigInt(block.number), gasLimit: Number(BigInt(block.gasLimit)) };
})();
// The largest transaction of the stack is the pool deploy, measured in spike S2 (not in this run).
const POOL_DEPLOY_GAS_S2 = 5_040_000;

const run = spawnSync("forge", args, { cwd: join(ROOT, "contracts"), encoding: "utf8" });
const output = `${run.stdout}\n${run.stderr}`;
if (run.status !== 0) {
  console.error(output);
  fail(`forge test exited ${run.status}; nothing recorded`);
}

// Logs look like: "  vouchedPay\n    call gas 2716879\n    tx gas   2744507"
const rows = [];
const re = /^\s{2}(\S.*?)\n\s+call gas (\d+)\n\s+tx gas\s+(\d+)$/gm;
for (const m of output.matchAll(re)) rows.push({ name: m[1], call: Number(m[2]), tx: Number(m[3]) });
const byName = Object.fromEntries(rows.map((r) => [r.name, r]));
for (const need of ["depositWithAuthorization", "vouchedPay", "sweep", "pool.transfer (no ledger)"]) {
  if (!byName[need]) fail(`no gas line for "${need}" in the forge output`);
}
const passed = output.match(/(\d+) passed; (\d+) failed; (\d+) skipped/);
if (!passed) fail("no test summary in the forge output");

const forgeVersion = execFileSync("forge", ["--version"], { encoding: "utf8" }).split("\n")[0];
const overhead = byName.vouchedPay.tx - byName["pool.transfer (no ledger)"].tx;
const fmt = (n) => n.toLocaleString("en-US");
const pct = (gas) => `${((gas / liveBlock.gasLimit) * 100).toFixed(1)}%`;
const lines = [
  "# Gas: step-1 exit check (fork)",
  "",
  "Generated by `node tools/record-fork-gas.mjs`. Do not edit by hand.",
  "",
  "| Field | Value |",
  "|---|---|",
  `| Class | fork (Foundry fork of Aevum testnet 44005, real tUSD8 bytecode, Gloam final verifiers) |`,
  `| Command | \`cd contracts && forge ${args.join(" ")}\` |`,
  `| Fork head at run | block ${forkBlock} |`,
  `| Commit | \`${git(["rev-parse", "HEAD"])}\`${git(["status", "--porcelain"]) ? " (working tree dirty)" : ""} |`,
  `| Toolchain | ${forgeVersion}, solc 0.8.24, evm shanghai, optimizer 200 runs |`,
  `| Machine | ${process.platform} ${process.arch}, node ${process.version} |`,
  `| Date | ${new Date().toISOString()} |`,
  `| Tests | ${passed[1]} passed, ${passed[2]} failed, ${passed[3]} skipped |`,
  "",
  "`call` = execution gas of the call (forge `lastCallGas`, each call isolated as its own transaction).",
  "`tx` = call + 21,000 + calldata gas (16 per non-zero byte, 4 per zero byte): a legacy transaction's gasUsed.",
  "",
  `Block gas limit on 44005: **${fmt(liveBlock.gasLimit)}** (live latest block ${liveBlock.number}, read by this script).`,
  "",
  "| Operation | call gas | tx gas | share of a block |",
  "|---|---:|---:|---:|",
  ...rows.map((r) => `| ${r.name} | ${fmt(r.call)} | ${fmt(r.tx)} | ${pct(r.tx)} |`),
  "",
  `Largest transaction of the stack: the Gloam pool deploy, ${fmt(POOL_DEPLOY_GAS_S2)} gas (spike S2, Aevum-rules`,
  `anvil, not this run) = ${pct(POOL_DEPLOY_GAS_S2)} of a block.`,
  "",
  `Ledger overhead per vouched pay (vouchedPay tx − pool.transfer tx, same proof): **${fmt(overhead)} gas**.`,
  "",
];
mkdirSync(join(ROOT, "evidence"), { recursive: true });
writeFileSync(join(ROOT, "evidence/fork-gas.md"), lines.join("\n"));
console.log(`✓ evidence/fork-gas.md: ${rows.length} operations, ledger overhead ${fmt(overhead)} gas`);
