#!/usr/bin/env node
// Revocations on `make fork` (D35): the gas of whole revoke transactions (legacy, 1 gwei) from a throwaway impersonated
// sender, what a second revoke and a bad secret do, and the deploy's gas from deployments/fork.json. Fork only; it
// refuses any other chain. Writes evidence/revocations-gas.md. Usage: node tools/revocations-gas.mjs [--rpc URL]
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const i = process.argv.indexOf("--rpc");
const RPC = i >= 0 ? process.argv[i + 1] : "http://127.0.0.1:8555";
const cast = (...a) => execFileSync("cast", [...a, "--rpc-url", RPC], { encoding: "utf8" }).trim();
const tryCast = (...a) => { try { return { ok: true, out: cast(...a) }; } catch (e) { return { ok: false, out: String(e.stderr ?? e.message) }; } };

if (cast("chain-id") !== "440050") { console.error("✗ fork only (chain 440050)"); process.exit(1); }
const dep = JSON.parse(readFileSync(join(ROOT, "deployments/fork.json"), "utf8"));
const R = dep.revocations?.address;
if (!R) { console.error("✗ deployments/fork.json has no revocations: make deploy-revocations-fork"); process.exit(1); }

const sender = `0x${randomBytes(20).toString("hex")}`;
cast("rpc", "anvil_setBalance", sender, "0xde0b6b3a7640000");
cast("rpc", "anvil_impersonateAccount", sender);
const FIELD = 21888242871839275222246405745257275088548364400416034343885157954420199247617n;
const secret = () => (BigInt(`0x${randomBytes(31).toString("hex")}`) % (FIELD - 1n)) + 1n;

const rows = [];
const revoke = (s, what) => {
  const r = JSON.parse(cast("send", R, "revoke(uint256)", s.toString(), "--from", sender, "--unlocked", "--legacy", "--gas-price", "1gwei", "--gas-limit", "200000", "--json"));
  const salt = cast("call", R, "saltOf(uint256)(uint256)", s.toString()).split(" ")[0];
  const at = cast("call", R, "revokedAt(uint256)(uint256)", salt).split(" ")[0];
  rows.push({ what, gasUsed: Number(BigInt(r.gasUsed)), type: r.type, status: r.status, block: Number(BigInt(r.blockNumber)), revokedAt: at, input: (r.input ?? "").length });
  return { s, salt };
};
const first = revoke(secret(), "revoke, a fresh salt");
revoke(secret(), "revoke, another fresh salt");
revoke(secret(), "revoke, a third fresh salt");
// A second revoke of the same secret: estimate and call both revert AlreadyRevoked; nothing to send.
const again = tryCast("estimate", R, "revoke(uint256)", first.s.toString(), "--from", sender);
const zero = tryCast("estimate", R, "revoke(uint256)", "0", "--from", sender);
const big = tryCast("estimate", R, "revoke(uint256)", FIELD.toString(), "--from", sender);
const est = cast("estimate", R, "revoke(uint256)", secret().toString(), "--from", sender);
cast("rpc", "anvil_stopImpersonatingAccount", sender);

const named = (r) => (r.ok ? `did not revert (${r.out})` : (r.out.match(/AlreadyRevoked|BadSecret|0x8cc1c533|0xe1dcd597/)?.[0] ?? r.out.split("\n")[0]).replace("0x8cc1c533", "AlreadyRevoked (0x8cc1c533)").replace("0xe1dcd597", "BadSecret (0xe1dcd597)"));
const gas = rows.map((r) => r.gasUsed);
const commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim();
const md = [
  "# Revocations: gas and refusals on the fork (D35)",
  "",
  `Generated by \`node tools/revocations-gas.mjs\` on \`make fork\` (chain 440050, a fork of Aevum 44005; Revocations deployed at fork block ${dep.revocations.block}), commit ${commit}, ${new Date().toISOString()}. Class: fork. Legacy transactions at 1 gwei from a throwaway impersonated sender.`,
  "",
  `Revocations ${R} over PoseidonT3 ${dep.revocations.poseidonT3}. Deploy: ${dep.revocations.gasUsed} gas (tx ${dep.revocations.txHash}, block ${dep.revocations.block}).`,
  "",
  "| Transaction | gasUsed | type | status | block | revokedAt after |",
  "|---|---:|---|---|---:|---:|",
  ...rows.map((r) => `| ${r.what} | ${r.gasUsed.toLocaleString("en-US")} | ${r.type} | ${r.status} | ${r.block} | ${r.revokedAt} |`),
  "",
  `A whole revoke tx: ${Math.min(...gas).toLocaleString("en-US")}–${Math.max(...gas).toLocaleString("en-US")} gas (21,000 base + calldata + the contract's work). eth_estimateGas for another fresh salt: ${Number(est).toLocaleString("en-US")}. At 1 gwei a revoke costs about ${(Math.max(...gas) / 1e9).toFixed(6)} of the native token. The relayer's cap for the revoke route is 200,000 gas.`,
  "",
  "Refusals (eth_estimateGas, nothing sent):",
  `- the same secret again: ${named(again)}`,
  `- secret 0: ${named(zero)}`,
  `- secret = the field order: ${named(big)}`,
  "",
].join("\n");
writeFileSync(join(ROOT, "evidence/revocations-gas.md"), md);
console.log(md);
process.exit(0);
