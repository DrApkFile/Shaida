#!/usr/bin/env node
// Bola (demo) opens live run 1's proof link in headless Chromium on the app configured for Aevum testnet (44005), types
// "Landlord Bola", sees the verdict, then runs "Check on-chain" (an eth_call; no transaction). Writes
// evidence/live-44005-ui/report-<width>.md and screenshots. Usage: node tools/ui-verify-live.mjs [--width 390]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { withChromium } from "./ui-cdp.mjs";

const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i >= 0 ? process.argv[i + 1] : d; };
const BASE = arg("base", "http://localhost:3100");
const WIDTH = Number(arg("width", "390"));
const REPO = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(REPO, "evidence/live-44005-ui");
const link = JSON.parse(readFileSync(join(REPO, "evidence/live-44005-run1.json"), "utf8")).link;
const log = [];
const note = (s) => { log.push(`${new Date().toISOString()} ${s}`); console.log(s); };

async function main() {
  mkdirSync(OUT, { recursive: true });
  await withChromium({ chromium: "/usr/bin/chromium", port: 9336, base: BASE, out: OUT, note }, async (_c, page) => {
    const bola = await page("bola", { width: WIDTH });
    await bola.goto("/");
    await bola.goto(link);
    await bola.type("input[name=reader]", "Landlord Bola");
    await bola.click("Verify");
    await bola.until(`document.querySelector("[data-verdict]")`, 180_000, "verdict");
    const v = await bola.eval(`({ verdict: document.querySelector("[data-verdict]").dataset.verdict, text: document.querySelector("[data-verdict]").innerText.replace(/\\s+/g, " ") })`);
    if (v.verdict !== "VALID") throw new Error(`verdict ${v.verdict}: ${v.text}`);
    note(`Bola on ${BASE} (Aevum testnet 44005): ${v.text.slice(0, 200)}`);
    await bola.click("Check on-chain");
    await bola.until(`document.querySelector(".on-chain-ok") || document.querySelector(".on-chain [role=alert]")`, 120_000, "on-chain check");
    const ok = await bola.eval(`(document.querySelector(".on-chain-ok") ?? document.querySelector(".on-chain [role=alert]")).innerText.replace(/\\s+/g, " ")`);
    if (!(await bola.eval(`!!document.querySelector(".on-chain-ok")`))) throw new Error(`on-chain check: ${ok}`);
    note(`Check on-chain: ${ok}`);
    await bola.shot(`${WIDTH}-verify-valid-44005`);
  });
}
const report = (ok, extra = "") => `# Live run 1: Bola verifies in the browser on Aevum testnet (${WIDTH} px)\n\nGenerated by \`node tools/ui-verify-live.mjs --width ${WIDTH}\` against the app configured for 44005. Personas are demo. No transaction is sent (the attest of this run is in evidence/live-44005-run1.md).\n\nResult: ${ok ? "passed" : `FAILED${extra}`}\n\n${log.map((l) => `- ${l}`).join("\n")}\n`;
main().then(
  () => { writeFileSync(join(OUT, `report-${WIDTH}.md`), report(true)); process.exit(0); },
  (e) => { note(`FAILED: ${e.message}`); writeFileSync(join(OUT, `report-${WIDTH}-FAILED-${Date.now()}.md`), report(false, `: ${e.message}`)); process.exit(1); },
);
