// Writes evidence/s8-browser.md from every report in results/ (spike S8). Numbers only, no recommendation.
// Usage: pnpm --filter @shaida/s8-bench record
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { reportSchema, type S8ReportFile } from "./src/report-schema.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "../../evidence/s8-browser.md");
const files = readdirSync(join(HERE, "results")).filter((f) => f.endsWith(".json")).sort();
if (files.length === 0) {
  console.error("✗ no reports in tools/s8-bench/results/: run the page first");
  process.exit(1);
}
const reports = files.map((f) => ({ file: f, r: reportSchema.parse(JSON.parse(readFileSync(join(HERE, "results", f), "utf8"))) }));

const sec = (v: number | null | undefined) => (v === null || v === undefined ? "—" : `${(v / 1000).toFixed(2)} s`);
const median = (xs: number[]) => {
  if (xs.length === 0) return null;
  const s = [...xs].sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2]! : (s[s.length / 2 - 1]! + s[s.length / 2]!) / 2;
};
type Run = S8ReportFile["runs"][number];
const warm = (r: S8ReportFile, v: string) => r.runs.filter((x) => x.variant === v && !x.cold && x.verified);
const cold = (r: S8ReportFile, v: string) => r.runs.find((x) => x.variant === v && x.cold);
const med = (runs: Run[], k: "witnessMs" | "proveMs" | "verifyMs" | "totalMs") => median(runs.map((x) => x[k]));
const device = (r: S8ReportFile) => r.label || "(no label)";

const lines: string[] = [
  "# Spike S8: browser proving time, 8 slots vs 4 slots",
  "",
  "Generated by `pnpm --filter @shaida/s8-bench record` from `tools/s8-bench/results/*.json`. Do not edit by hand.",
  "",
  "**THROWAWAY KEYS** (one local contribution each; never deployed or published). Proving time does not depend on",
  "who made the key, so these numbers carry over to the ceremony key of the same circuit.",
  "",
  "Each run: a random valid witness with every slot used, built in the page; then witness calculation, Groth16 prove",
  "and verify in a Web Worker (snarkjs 0.7.6 browser build). Total = witness + prove + verify. Medians are over warm",
  "runs (the first run of each variant also fetched its wasm and zkey and set up the curve; shown separately).",
  "Medians use verified runs only; \"All runs\" lists every run with its verification result.",
  "",
  "## Summary (total = witness + prove + verify)",
  "",
  "| Device | Logical CPUs | 8 slots, warm median | 4 slots, warm median | 4 / 8 | 8 slots, cold | 4 slots, cold | Report |",
  "|---|---:|---:|---:|---:|---:|---:|---|",
];
for (const { file, r } of reports) {
  const t8 = med(warm(r, "income8"), "totalMs");
  const t4 = med(warm(r, "income4"), "totalMs");
  const ratio = t8 && t4 ? (t4 / t8).toFixed(2) : "—";
  const c8 = cold(r, "income8")?.totalMs;
  const c4 = cold(r, "income4")?.totalMs;
  lines.push(
    `| ${device(r)} | ${r.hardwareConcurrency ?? "—"} | ${sec(t8)} | ${sec(t4)} | ${ratio} | ${sec(c8)} | ${sec(c4)} | \`${file}\` |`,
  );
}
lines.push("");

for (const { file, r } of reports) {
  const m = r.manifest;
  lines.push(`## ${device(r)}`, "");
  lines.push("| Field | Value |", "|---|---|");
  lines.push(`| Report | \`tools/s8-bench/results/${file}\` |`);
  lines.push(`| User agent | ${r.userAgent} |`);
  lines.push(`| navigator.hardwareConcurrency | ${r.hardwareConcurrency ?? "—"} |`);
  lines.push(`| navigator.deviceMemory | ${r.deviceMemoryGiB === null ? "— (not exposed)" : `${r.deviceMemoryGiB} GiB (rounded by the browser)`} |`);
  if (r.host) lines.push(`| Host (headless run) | ${r.host.cpuModel}, ${r.host.logicalCpus} logical CPUs, ${r.host.ramGiB} GiB RAM, ${r.host.browser} |`);
  lines.push(`| Page built from | commit \`${m.commit}\`${m.dirty ? " (working tree dirty)" : ""}, ${m.compiler}, ${m.builtAt} |`);
  lines.push(`| Run | ${r.startedAt} → ${r.finishedAt} |`);
  for (const [name, v] of Object.entries(m.variants)) {
    lines.push(`| ${name} | ${v.slots} slots, ${v.constraints.toLocaleString("en-US")} constraints, zkey ${(v.zkeyBytes / 2 ** 20).toFixed(1)} MiB, r1cs \`${v.r1csSha256.slice(0, 16)}…\` |`);
  }
  if (r.errors.length) lines.push(`| Errors | ${r.errors.join("; ")} |`);
  lines.push("", "| Slots | warm runs | witness | prove | verify | total | cold: zkey load | cold: wasm load | cold: curve init | cold total |");
  lines.push("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
  for (const v of ["income8", "income4"] as const) {
    const w = warm(r, v);
    const c = cold(r, v);
    lines.push(
      `| ${v === "income8" ? 8 : 4} | ${w.length} | ${sec(med(w, "witnessMs"))} | ${sec(med(w, "proveMs"))} | ${sec(med(w, "verifyMs"))} | ${sec(med(w, "totalMs"))} | ${sec(c?.zkeyLoadMs)} | ${sec(c?.wasmLoadMs)} | ${sec(c?.curveInitMs)} | ${sec(c?.totalMs)} |`,
    );
  }
  lines.push("", "<details><summary>All runs</summary>", "", "| Slots | run | cold | input | witness | prove | verify | total | verified |", "|---:|---:|---|---:|---:|---:|---:|---:|---|");
  for (const x of r.runs) {
    lines.push(`| ${x.variant === "income8" ? 8 : 4} | ${x.run} | ${x.cold ? "yes" : ""} | ${sec(x.inputMs)} | ${sec(x.witnessMs)} | ${sec(x.proveMs)} | ${sec(x.verifyMs)} | ${sec(x.totalMs)} | ${x.verified ? "yes" : "NO"} |`);
  }
  lines.push("", "</details>", "");
}
writeFileSync(OUT, lines.join("\n"));
console.log(`✓ evidence/s8-browser.md from ${reports.length} report(s)`);
