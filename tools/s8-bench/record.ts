// Writes evidence/s8-browser.md from every report in results/ (spike S8) and every builder-reported result in
// results/reported/. Numbers only, no recommendation. Usage: pnpm --filter @shaida/s8-bench record
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { reportedSchema, reportSchema, type S8ReportFile } from "./src/report-schema.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "../../evidence/s8-browser.md");
const jsonIn = (dir: string) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")).sort() : []);
const read = (dir: string, f: string): unknown => JSON.parse(readFileSync(join(dir, f), "utf8"));
const pages = jsonIn(join(HERE, "results")).map((f) => ({ file: f, r: reportSchema.parse(read(join(HERE, "results"), f)) }));
const reported = jsonIn(join(HERE, "results/reported")).map((f) => ({ file: `reported/${f}`, r: reportedSchema.parse(read(join(HERE, "results/reported"), f)) }));
if (pages.length + reported.length === 0) {
  console.error("✗ no reports in tools/s8-bench/results/: run the page first");
  process.exit(1);
}

const VARIANTS = ["income4", "income8"] as const;
type V = (typeof VARIANTS)[number];
const slotsOf = (v: string) => (v === "income8" ? 8 : 4);
const sec = (v: number | null | undefined) => (v === null || v === undefined ? "—" : `${(v / 1000).toFixed(2)} s`);
const median = (xs: number[]) => {
  if (xs.length === 0) return null;
  const s = [...xs].sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2]! : (s[s.length / 2 - 1]! + s[s.length / 2]!) / 2;
};
type Run = S8ReportFile["runs"][number];
const perRun = (r: S8ReportFile) => r.schema === "shaida-s8/2";
/** /1: warm runs (the first run of a variant in the shared worker is excluded). /2: every run (fresh worker each). */
const counted = (r: S8ReportFile, v: V) => r.runs.filter((x) => x.variant === v && x.verified && (perRun(r) || !x.cold));
const first = (runs: readonly { variant: string; run: number; totalMs: number }[], v: V) => runs.find((x) => x.variant === v && x.run === 1)?.totalMs;
const med = (runs: Run[], k: "witnessMs" | "proveMs" | "verifyMs" | "totalMs") => median(runs.map((x) => x[k]));
const device = (r: { label: string }) => r.label || "(no label)";
const basis = (r: S8ReportFile) => (perRun(r) ? "all runs, fresh worker each" : "warm runs (run 1 excluded)");
const state = (r: S8ReportFile) => (r.complete === false ? " (partial: the page did not finish)" : "");

const lines: string[] = [
  "# Spike S8: browser proving time, 4 slots vs 8 slots",
  "",
  "Generated by `pnpm --filter @shaida/s8-bench record` from `tools/s8-bench/results/*.json` (saved by the page) and",
  "`tools/s8-bench/results/reported/*.json` (reported by the builder by hand, marked **reported**). Do not edit by hand.",
  "",
  "**THROWAWAY KEYS** (one local contribution each; never deployed or published). Proving time does not depend on",
  "who made the key, so these numbers carry over to the ceremony key of the same circuit. Since D12 the production",
  "circuit is the 4-slot one; its r1cs is byte-identical to the 4-slot variant measured here before D12.",
  "",
  "Each run: a random valid witness with every slot used, built in the page; then witness calculation, Groth16 prove",
  "and verify in a Web Worker (snarkjs 0.7.6 browser build). Total = witness + prove + verify; fetching the wasm and",
  "zkey and setting up the curve are timed separately. Report format shaida-s8/1 used one worker for the whole page",
  "(so run 1 of each variant was cold); shaida-s8/2 starts a fresh worker for every run. Medians use verified runs.",
  "",
  "## Summary (total = witness + prove + verify)",
  "",
  "| Device | Source | Logical CPUs | 4 slots, median | 8 slots, median | 4 / 8 | 4 slots, run 1 | 8 slots, run 1 | Median over | Report |",
  "|---|---|---:|---:|---:|---:|---:|---:|---|---|",
];
for (const { file, r } of pages) {
  const [t4, t8] = VARIANTS.map((v) => med(counted(r, v), "totalMs"));
  const ratio = t8 && t4 ? (t4 / t8).toFixed(2) : "—";
  lines.push(
    `| ${device(r)} | page${state(r)} | ${r.hardwareConcurrency ?? "—"} | ${sec(t4)} | ${sec(t8)} | ${ratio} | ${sec(first(r.runs, "income4"))} | ${sec(first(r.runs, "income8"))} | ${basis(r)} | \`${file}\` |`,
  );
}
for (const { file, r } of reported) {
  const [t4, t8] = VARIANTS.map((v) => median(r.runs.filter((x) => x.variant === v && x.verified).map((x) => x.totalMs)));
  const ratio = t8 && t4 ? (t4 / t8).toFixed(2) : "—";
  lines.push(
    `| ${device(r)} | **reported** | — | ${sec(t4)} | ${sec(t8)} | ${ratio} | ${sec(first(r.runs, "income4"))} | ${sec(first(r.runs, "income8"))} | the reported runs | \`${file}\` |`,
  );
}
lines.push("");

for (const { file, r } of reported) {
  lines.push(`## ${device(r)} (reported)`, "", "| Field | Value |", "|---|---|");
  lines.push(`| Report | \`tools/s8-bench/results/${file}\` |`);
  lines.push(`| Source | ${r.source} |`);
  lines.push(`| Reported | ${r.reportedAt} |`);
  lines.push(`| Page built from | ${r.pageCommit ? `commit \`${r.pageCommit}\`` : "—"} |`);
  for (const n of r.notes) lines.push(`| Note | ${n} |`);
  lines.push("", "| Slots | run | cold | total | verified |", "|---:|---:|---|---:|---|");
  for (const x of r.runs) lines.push(`| ${slotsOf(x.variant)} | ${x.run} | ${x.cold ? "yes" : ""} | ${sec(x.totalMs)} | ${x.verified ? "yes" : "NO"} |`);
  lines.push("");
}

for (const { file, r } of pages) {
  const m = r.manifest;
  lines.push(`## ${device(r)}${state(r)}`, "");
  lines.push("| Field | Value |", "|---|---|");
  lines.push(`| Report | \`tools/s8-bench/results/${file}\` (${r.schema}) |`);
  lines.push(`| User agent | ${r.userAgent} |`);
  lines.push(`| navigator.hardwareConcurrency | ${r.hardwareConcurrency ?? "—"} |`);
  lines.push(`| navigator.deviceMemory | ${r.deviceMemoryGiB === null ? "— (not exposed)" : `${r.deviceMemoryGiB} GiB (rounded by the browser)`} |`);
  if (r.host) lines.push(`| Host (headless run) | ${r.host.cpuModel}, ${r.host.logicalCpus} logical CPUs, ${r.host.ramGiB} GiB RAM, ${r.host.browser} |`);
  lines.push(`| Page built from | commit \`${m.commit}\`${m.dirty ? " (working tree dirty)" : ""}, ${m.compiler}, ${m.builtAt} |`);
  lines.push(`| Run | ${r.startedAt} → ${r.finishedAt} |`);
  for (const [name, v] of Object.entries(m.variants)) {
    lines.push(`| ${name} | ${v.slots} slots, ${v.constraints.toLocaleString("en-US")} constraints, zkey ${(v.zkeyBytes / 2 ** 20).toFixed(1)} MiB, r1cs \`${v.r1csSha256.slice(0, 16)}…\` |`);
  }
  if (r.errors.length) lines.push(`| Errors | ${r.errors.join("; ")} |`);
  lines.push("", `Medians over ${basis(r)}:`, "");
  lines.push("| Slots | runs | witness | prove | verify | total | run 1: zkey load | run 1: wasm load | run 1: curve init | run 1 total |");
  lines.push("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
  for (const v of VARIANTS) {
    const w = counted(r, v);
    const c = r.runs.find((x) => x.variant === v && x.run === 1);
    lines.push(
      `| ${slotsOf(v)} | ${w.length} | ${sec(med(w, "witnessMs"))} | ${sec(med(w, "proveMs"))} | ${sec(med(w, "verifyMs"))} | ${sec(med(w, "totalMs"))} | ${sec(c?.zkeyLoadMs)} | ${sec(c?.wasmLoadMs)} | ${sec(c?.curveInitMs)} | ${sec(c?.totalMs)} |`,
    );
  }
  lines.push("", "<details><summary>All runs</summary>", "", "| Slots | run | cold | input | witness | prove | verify | total | verified |", "|---:|---:|---|---:|---:|---:|---:|---:|---|");
  for (const x of r.runs) {
    lines.push(`| ${slotsOf(x.variant)} | ${x.run} | ${x.cold ? "yes" : ""} | ${sec(x.inputMs)} | ${sec(x.witnessMs)} | ${sec(x.proveMs)} | ${sec(x.verifyMs)} | ${sec(x.totalMs)} | ${x.verified ? "yes" : "NO"} |`);
  }
  lines.push("", "</details>", "");
}
writeFileSync(OUT, lines.join("\n"));
console.log(`✓ evidence/s8-browser.md from ${pages.length} page report(s) and ${reported.length} reported result(s)`);
