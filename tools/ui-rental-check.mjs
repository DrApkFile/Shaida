#!/usr/bin/env node
// examples/rental-check in headless Chromium at 390 px against the fork fixture: builds the page with esbuild (the
// example's own bundler), serves it, serves the fixture replay RPC, then pastes each fixture link and reads the
// decision the page shows. Read-only; no wallet. Writes evidence/sdk/rental-check-390.md and screenshots.
// With --live, also run 1's link against Aevum 44005 itself (the public RPC; read-only).
// Usage: node tools/ui-rental-check.mjs [--chromium /usr/bin/chromium] [--width 390] [--live]
import { spawn } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { sleep, withChromium } from "./ui-cdp.mjs";

const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i >= 0 ? (process.argv[i + 1] ?? d) : d; };
const CHROMIUM = arg("chromium", "/usr/bin/chromium");
const WIDTH = Number(arg("width", "390"));
const LIVE = process.argv.includes("--live");
const REPO = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(REPO, "evidence/sdk");
const log = [];
const note = (l) => { log.push(l); console.log(l); };
const children = [];
const start = (cmd, args, cwd, ready) => new Promise((ok, bad) => {
  const c = spawn(cmd, args, { cwd, stdio: ["pipe", "pipe", "pipe"] }); // esbuild --serve stops when its stdin closes
  children.push(c);
  let seen = "";
  const on = (b) => { seen += b.toString(); if (ready.test(seen)) ok(seen); };
  c.stdout.on("data", on);
  c.stderr.on("data", on);
  c.once("exit", (code) => bad(new Error(`${cmd} ${args.join(" ")} exited ${code}: ${seen.slice(-400)}`)));
});

async function main() {
  mkdirSync(OUT, { recursive: true });
  await start("pnpm", ["--filter", "@shaida/sdk", "fixture-rpc"], REPO, /SHAIDA_NETWORK=/);
  note("fixture RPC: replay of the fork run on http://127.0.0.1:8565 (packages/sdk/test/fixture-rpc.ts)");
  await start("pnpm", ["--filter", "@shaida/examples", "rental-check"], REPO, /127\.0\.0\.1:8566/);
  note("examples/rental-check served by esbuild on http://127.0.0.1:8566 (app.js bundled with @shaida/sdk only)");
  const run1 = (await import(join(REPO, "web/src/app/example-links.json"), { with: { type: "json" } })).default["44005"].link;
  const links = (await import(join(REPO, "tools/privacy/fixtures/fork-truth-fixes.json"), { with: { type: "json" } })).default.links;
  const cases = [
    ["Ada's link, made out to Landlord Bola", links.find((l) => l.name === "ada").from.url, "Landlord Bola", "APPROVE", "rental-01-approve"],
    ["Chidi's link (made out to Lender Dayo), typed as Landlord Bola", links.find((l) => l.name === "chidi").from.url, "Landlord Bola", "DECLINE", "rental-02-wrong-reader"],
    ["Ada's link with its threshold edited", edited(links.find((l) => l.name === "ada").from.url), "Landlord Bola", "DECLINE", "rental-03-edited"],
  ].map((c) => [...c, "fork"]);
  if (LIVE) cases.push(["Run 1's link on Aevum 44005 (live RPC), made out to Landlord Bola", run1, "Landlord Bola", "APPROVE", "rental-04-live-44005", "aevum"]);
  await withChromium({ chromium: CHROMIUM, port: 9338, base: "http://127.0.0.1:8566", out: OUT, note }, async (_c, page) => {
    const p = await page("landlord", { width: WIDTH });
    await p.goto("/");
    for (const [what, link, reader, want, shot, network] of cases) {
      await p.type("textarea[name=link]", `https://shaida.onrender.com${link}`);
      await p.type("input[name=reader]", reader);
      await p.type("select[name=network]", network);
      await p.eval(`document.getElementById("result").textContent = ""`);
      await p.click("Check income");
      await p.until(`["APPROVE","DECLINE","INCONCLUSIVE","ERROR"].includes(document.getElementById("result").dataset.kind) && document.getElementById("result").textContent`, 120_000, "a decision");
      const got = await p.eval(`({ kind: document.getElementById("result").dataset.kind, text: document.getElementById("result").innerText.replace(/\\s+/g, " ") })`);
      if (got.kind !== want) throw new Error(`${what}: ${got.kind} (${got.text}), expected ${want}`);
      note(`${what} → ${got.kind}: ${got.text.slice(0, 220)}`);
      await p.shot(`${shot}-${WIDTH}`);
    }
  });
}

function edited(url) {
  const j = JSON.parse(Buffer.from(url.split("#")[1], "base64url"));
  j.proofs[0].publicSignals[2] = "4000000";
  return `/v#${Buffer.from(JSON.stringify(j)).toString("base64url")}`;
}

let ok = false;
try { await main(); ok = true; } catch (e) { note(`FAILED: ${e.message}`); }
for (const c of children) c.kill();
await sleep(300);
const name = ok ? `rental-check-${WIDTH}.md` : `rental-check-${WIDTH}-FAILED-${new Date().toISOString().replace(/[:.]/g, "-")}.md`;
writeFileSync(join(OUT, name), `# examples/rental-check at ${WIDTH} px against the fork fixture${LIVE ? " and 44005" : ""}\n\nGenerated by \`node tools/ui-rental-check.mjs --width ${WIDTH}${LIVE ? " --live" : ""}\` on ${new Date().toISOString()}. Headless Chromium; the page runs @shaida/sdk in the browser against the fork fixture replayed as JSON-RPC (not a chain; IncomeVerifier is not called)${LIVE ? ", and against Aevum testnet 44005 through the public RPC (read-only)" : ""}. Personas are demo. Read-only.\n\nResult: ${ok ? "passed" : "FAILED"}\n\n${log.map((l) => `- ${l}`).join("\n")}\n`);
process.exit(ok ? 0 : 1);
