#!/usr/bin/env node
// Withdrawals through the real UI on `make fork`, in headless Chromium at --width (390 by default). Ada (demo) makes a
// vault and a receive address; scripts/fork-pay-to.ts pays it (Acme 3 + 4 + 2 tUSD8, Mallory 5 unvouched); Ada sweeps
// all in Inbox, then in Withdraw picks Acme's three notes and withdraws them in one batch to a fresh address, which
// must then hold 9 tUSD8 by the chain. Screenshots and report go to evidence/ui-withdraw/.
// Usage: node tools/ui-flow-withdraw.mjs [--width 390]
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { withChromium } from "./ui-cdp.mjs";

const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i >= 0 ? process.argv[i + 1] : d; };
const BASE = arg("base", "http://localhost:3100");
const CHROMIUM = arg("chromium", "/usr/bin/chromium");
const WIDTH = Number(arg("width", "390"));
const RPC = "http://127.0.0.1:8555";
const TUSD8 = "0x456569838f1d43009A91ebA4263147Afd7233483";
const REPO = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(REPO, "evidence/ui-withdraw");
const PASS = "demo passphrase 1";
const log = [];
const note = (s) => { log.push(`${new Date().toISOString()} ${s}`); console.log(s); };
const cast = (...a) => execFileSync("cast", [...a, "--rpc-url", RPC], { encoding: "utf8" }).trim();

async function main() {
  mkdirSync(OUT, { recursive: true });
  if (cast("chain-id") !== "440050") throw new Error("not make fork");
  const fresh = cast("wallet", "new", "--json").match(/"address":\s*"(0x[0-9a-fA-F]{40})"/)?.[1];
  if (!fresh) throw new Error("no fresh address");
  await withChromium({ chromium: CHROMIUM, port: 9335, base: BASE, out: OUT, note }, async (_c, page) => {
    const ada = await page("ada", { width: WIDTH });
    await ada.goto("/app/inbox");
    await ada.type("input[type=password]", PASS);
    await ada.click("Create vault");
    await ada.click("Create receive address");
    await ada.until(`document.querySelector(".receive-tag")`, 30_000, "receive address");
    const tag = await ada.eval(`document.querySelector(".receive-tag").innerText.trim()`);
    execFileSync("pnpm", ["--silent", "--filter", "@shaida/pay", "exec", "tsx", "scripts/fork-pay-to.ts", "--tag", tag], { cwd: REPO, encoding: "utf8" });
    note("paid Ada's browser receive address: Acme 3 + 4 + 2 tUSD8 (vouched), Mallory 5 tUSD8 (unvouched)");
    await ada.goto("/app/inbox");
    await ada.type("input[type=password]", PASS);
    await ada.click("Unlock");
    await ada.until(`document.querySelectorAll(".payment").length === 4`, 180_000, "4 payments");
    await ada.click("Sweep all");
    await ada.until(`document.querySelectorAll(".payment .state.swept").length === 3 || document.querySelector("section[aria-labelledby=payments] [role=alert]")`, 900_000, "3 swept");
    note("inbox: Acme's 3 payments swept (Mallory's is not vouched, so not sweepable here)");

    await ada.eval(`document.querySelector('.section-tabs a[href="/app/withdraw"]').click()`);
    await ada.until(`document.querySelectorAll(".withdraw-note").length === 3`, 120_000, "3 swept notes in Withdraw");
    note(`withdraw page: ${await ada.eval(`[...document.querySelectorAll(".withdraw-note")].map(li => li.innerText.replace(/\\s+/g, " ")).join(" | ")`)}`);
    note(`warning shown: "${await ada.eval(`document.querySelector(".notice.warn strong").innerText`)}"`);
    await ada.eval(`document.querySelectorAll(".withdraw-note input[type=checkbox]").forEach(b => b.click())`);
    await ada.type("input[name=to]", fresh);
    await ada.shot(`${WIDTH}-01-withdraw-picked`);
    await ada.click("Withdraw 3 notes (9 tUSD8)");
    await ada.until(`[...document.querySelectorAll(".withdraw-note .state")].filter(s => s.innerText.startsWith("withdrawn")).length === 3 || document.querySelector("section[aria-labelledby=withdraw] [role=alert]")`, 900_000, "3 withdrawn");
    const alert = await ada.eval(`document.querySelector("section[aria-labelledby=withdraw] [role=alert]")?.innerText ?? ""`);
    if (alert) throw new Error(`withdraw refused: ${alert}`);
    await ada.shot(`${WIDTH}-02-withdrawn`);
  });
  const bal = cast("call", TUSD8, "balanceOf(address)(uint256)", fresh).split(" ")[0];
  if (bal !== "9000000") throw new Error(`fresh address holds ${bal}, expected 9000000`);
  note(`chain: the fresh address ${fresh} holds ${Number(bal) / 1e6} tUSD8`);
}

const report = (ok, extra = "") => `# UI flow, withdrawals on make fork (${WIDTH} px)\n\nGenerated by \`node tools/ui-flow-withdraw.mjs --width ${WIDTH}\`. Personas are demo.\n\nResult: ${ok ? "passed" : `FAILED${extra}`}\n\n${log.map((l) => `- ${l}`).join("\n")}\n`;
main().then(
  () => { writeFileSync(join(OUT, `report-${WIDTH}.md`), report(true)); process.exit(0); },
  (e) => { note(`FAILED: ${e.message}`); writeFileSync(join(OUT, `report-${WIDTH}-FAILED-${Date.now()}.md`), report(false, `: ${e.message}`)); process.exit(1); },
);
