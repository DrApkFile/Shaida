// Writes evidence/income-circuit.md: constraint counts (from this compile), the THROWAWAY key's size, Node proving
// time, and the Shanghai check of the snarkjs verifier generated from that key. Every number comes from this run.
// Usage: PTAU_PATH=/path/to/powersOfTau28_hez_final_17.ptau pnpm --filter @shaida/proofs bench
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, statSync, writeFileSync, copyFileSync } from "node:fs";
import { cpus, totalmem } from "node:os";
import { join } from "node:path";
import * as snarkjs from "snarkjs";
import { buildIncomeWitness, type CircuitInput } from "../src/index.js";
import { BUILD, endSnarkjs, PKG } from "../test/helpers/circuit.js";
import { honestRequest, makeScenario, Rng } from "../test/helpers/scenario.js";
import { ensureThrowawayKey, THROWAWAY } from "./throwaway.js";

const REPO = join(PKG, "../..");
const RUNS = 3;
const fail = (msg: string): never => {
  console.error(`✗ bench: ${msg}`);
  process.exit(1);
};
const ptau = process.env.PTAU_PATH ?? fail("INCONCLUSIVE: set PTAU_PATH to the Hermez 2^17 ptau (CEREMONY.md)");

// 1. compile, and take the counts from circom's own output
const compile = spawnSync(process.execPath, ["scripts/compile.mjs"], { cwd: PKG, encoding: "utf8" });
if (compile.status !== 0) fail(`compile failed:\n${compile.stdout}${compile.stderr}`);
const count = (label: string) => Number(compile.stdout.match(new RegExp(`^${label}: (\\d+)$`, "m"))?.[1] ?? fail(label));
const nonLinear = count("non-linear constraints");
const linear = count("linear constraints");
const publicInputs = count("public inputs");
const domain = nonLinear + linear + publicInputs + 1;

// 2. throwaway key
const key = await ensureThrowawayKey(ptau);
const vkey = JSON.parse(readFileSync(key.vkey, "utf8")) as snarkjs.VerificationKey;

// 3. Node proving time, witness generation included (groth16.fullProve)
function witnessFor(payments: number): CircuitInput {
  const rng = new Rng(1000 + payments);
  const s = makeScenario(rng, { payments });
  const r = buildIncomeWitness(honestRequest(s, rng, { threshold: 1n }));
  return r.ok ? r.value.input : fail(`builder: ${r.error.code}`);
}
const timings: { slots: number; ms: number[] }[] = [];
for (const slots of [1, 8]) {
  const input = witnessFor(slots);
  const ms: number[] = [];
  for (let i = 0; i < RUNS; i++) {
    const t0 = performance.now();
    const { proof, publicSignals } = await snarkjs.groth16.fullProve(input, join(BUILD, "income_js/income.wasm"), key.zkey);
    ms.push(performance.now() - t0);
    if (!(await snarkjs.groth16.verify(vkey, publicSignals, proof))) fail(`a ${slots}-slot proof did not verify`);
  }
  timings.push({ slots, ms });
}
await endSnarkjs();

// 4. Shanghai check of the generated verifier (compiled alone, solc 0.8.24, evm shanghai)
const forgeDir = join(THROWAWAY, "forge");
mkdirSync(join(forgeDir, "src"), { recursive: true });
copyFileSync(key.verifierSol, join(forgeDir, "src/IncomeVerifierThrowaway.sol")); // compiled alone, under a fixed name
writeFileSync(
  join(forgeDir, "foundry.toml"),
  '[profile.default]\nsrc = "src"\nout = "out"\nsolc_version = "0.8.24"\nevm_version = "shanghai"\noptimizer = true\noptimizer_runs = 200\n',
);
const forge = spawnSync("forge", ["build", "--root", forgeDir, "--sizes"], { encoding: "utf8" });
if (forge.status !== 0) fail(`forge build of the verifier failed:\n${forge.stdout}${forge.stderr}`);
const check = spawnSync(process.execPath, ["tools/check-shanghai.mjs", join(forgeDir, "out")], { cwd: REPO, encoding: "utf8" });
if (check.status !== 0) fail(`Shanghai check failed:\n${check.stdout}${check.stderr}`);
const runtimeSize = forge.stdout.match(/Groth16Verifier\s*\|\s*([\d,]+)/)?.[1] ?? "—";

// 5. write the evidence file
const git = (a: string[]) => execFileSync("git", a, { cwd: REPO, encoding: "utf8" }).trim();
const sha256 = (f: string) => createHash("sha256").update(readFileSync(f)).digest("hex");
const median = (xs: number[]) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)]!;
const sec = (ms: number) => `${(ms / 1000).toFixed(2)} s`;
const cpu = cpus();
const lines = [
  "# Income circuit: size, throwaway key, Node proving time",
  "",
  "Generated by `PTAU_PATH=… pnpm --filter @shaida/proofs bench` (scripts/bench-proving.ts). Do not edit by hand.",
  "",
  "**THROWAWAY KEY.** One phase-2 contribution with random entropy, made on this machine for timing and tests. Whoever",
  "ran it could forge proofs: it is never deployed or published. The real key comes from the ceremony (CEREMONY.md).",
  "",
  "| Field | Value |",
  "|---|---|",
  "| Class | local (Node, this machine), throwaway key |",
  `| Circuit | circuits/income.circom sha256 \`${sha256(join(PKG, "circuits/income.circom"))}\`, circuits/lib/income_template.circom sha256 \`${sha256(join(PKG, "circuits/lib/income_template.circom"))}\` |`,
  `| Compiler | ${compile.stdout.match(/circom compiler [\d.]+/)?.[0] ?? "—"}, \`--O2\` |`,
  `| Constraints | ${nonLinear.toLocaleString("en-US")} non-linear, ${linear.toLocaleString("en-US")} linear; ${publicInputs} public inputs |`,
  `| Fits 2^17? | ${domain <= 131072 ? "yes" : "NO"}: constraints + public inputs + 1 = ${domain.toLocaleString("en-US")} of 131,072 |`,
  `| r1cs sha256 | \`${sha256(join(BUILD, "income.r1cs"))}\` |`,
  `| Throwaway zkey | ${statSync(key.zkey).size.toLocaleString("en-US")} bytes (${(statSync(key.zkey).size / 2 ** 20).toFixed(1)} MiB) |`,
  `| Setup + 1 contribution | ${key.setupMs === null ? "— (key reused from an earlier run on the same r1cs)" : sec(key.setupMs)} |`,
  `| Verifier (snarkjs) | ${check.stdout.trim()} Runtime size ${runtimeSize} bytes. |`,
  `| Machine | ${cpu[0]?.model.replace(/\s+/g, " ") ?? "—"}, ${cpu.length} logical CPUs, ${(totalmem() / 2 ** 30).toFixed(1)} GiB RAM, ${process.platform} ${process.arch}, node ${process.version} |`,
  `| Commit | \`${git(["rev-parse", "HEAD"])}\`${git(["status", "--porcelain"]) ? " (working tree dirty)" : ""} |`,
  `| Date | ${new Date().toISOString()} |`,
  "",
  `Node proving time, \`snarkjs.groth16.fullProve\` (witness + proof), ${RUNS} runs each, every proof verified:`,
  "",
  "| Used slots | runs | median |",
  "|---:|---|---:|",
  ...timings.map((t) => `| ${t.slots} | ${t.ms.map(sec).join(", ")} | ${sec(median(t.ms))} |`),
  "",
];
writeFileSync(join(REPO, "evidence/income-circuit.md"), lines.join("\n"));
console.log(`✓ evidence/income-circuit.md (${nonLinear} constraints, median 8-slot ${sec(median(timings[1]!.ms))})`);
process.exit(0); // snarkjs workers keep Node alive otherwise
