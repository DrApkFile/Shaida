// Publishing rehearsal (nothing is published): the tarball from scripts/pack.mjs, install the tarball into an empty project with npm, run
// examples/verify-node.mjs from there against Aevum 44005 (read-only), typecheck a consumer under nodenext with
// skipLibCheck off, and list the installed licences. Writes evidence/sdk/pack.md. Usage: pnpm --filter shaida-sdk pack-check
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { packTarball } from "./pack.mjs";

const PKG = fileURLToPath(new URL("..", import.meta.url));
const REPO = join(PKG, "../..");
// npm runs as an integrator's would: without the npm_config_* that pnpm sets for its own scripts.
const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !/^npm_/i.test(k) && k !== "PNPM_SCRIPT_SRC_DIR"));
const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, env, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
const dir = mkdtempSync(join(tmpdir(), "shaida-sdk-pack-"));
const lines = [];
try {
  const packed = packTarball(dir, env);
  const tgz = packed.path;
  const sha256 = createHash("sha256").update(readFileSync(tgz)).digest("hex");
  lines.push(`scripts/pack.mjs (npm pack of the staged package): ${packed.filename}, ${packed.size} bytes packed, ${packed.unpackedSize} unpacked, ${packed.entryCount} files, sha256 ${sha256}, ${packed.integrity}`);
  const shipped = JSON.parse(run("tar", ["-xOzf", tgz, "package/package.json"], dir));
  lines.push(`shipped package.json: name ${shipped.name}, version ${shipped.version}, keys ${Object.keys(shipped).join(", ")}; no devDependencies, no scripts, no workspace: or @shaida/ specifier`);
  lines.push(`files: ${packed.files.map((f) => f.path).sort().join(", ")}`);
  const app = join(dir, "clean");
  mkdirSync(app);
  writeFileSync(join(app, "package.json"), '{"name":"clean-integrator","private":true,"type":"module"}\n');
  run("npm", ["install", "--no-audit", "--no-fund", tgz], app);
  const licences = new Map();
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      if (n.startsWith(".")) continue;
      const p = join(d, n);
      if (n.startsWith("@")) { walk(p); continue; }
      if (!existsSync(join(p, "package.json"))) continue;
      const j = JSON.parse(readFileSync(join(p, "package.json"), "utf8"));
      const l = typeof j.license === "string" ? j.license : JSON.stringify(j.license ?? j.licenses ?? "none");
      licences.set(l, [...(licences.get(l) ?? []), `${j.name} ${j.version}`]);
      if (existsSync(join(p, "node_modules"))) walk(join(p, "node_modules"));
    }
  };
  walk(join(app, "node_modules"));
  const total = [...licences.values()].reduce((s, v) => s + v.length, 0);
  lines.push(`clean install (npm ${run("npm", ["-v"], app).trim()}, node ${process.version}): ${total} packages`);
  for (const [l, ps] of [...licences].sort((a, b) => b[1].length - a[1].length)) lines.push(`licence ${l} (${ps.length}): ${ps.sort().join(", ")}`);
  copyFileSync(join(REPO, "examples/verify-node.mjs"), join(app, "verify-node.mjs"));
  const link = JSON.parse(readFileSync(join(REPO, "web/src/app/example-links.json"), "utf8"))["44005"].link;
  lines.push(`examples/verify-node.mjs from the clean install, run 1 on 44005, "Landlord Bola": ${run(process.execPath, ["verify-node.mjs", `https://shaida.onrender.com${link}`, "Landlord Bola"], app).trim()}`);
  writeFileSync(join(app, "consumer.ts"), 'import { verifyIncomeLink, type Verification } from "shaida-sdk";\nconst v: Verification = await verifyIncomeLink("#x", { readerName: "a", network: "aevum-testnet" });\nif (v.status === "VALID") { const t: bigint = v.threshold; console.log(t); } else console.log(v.code);\n');
  writeFileSync(join(app, "tsconfig.json"), '{"compilerOptions":{"module":"nodenext","moduleResolution":"nodenext","target":"es2022","strict":true,"noEmit":true,"skipLibCheck":false,"types":[]},"files":["consumer.ts"]}\n');
  run(process.execPath, [join(PKG, "node_modules/typescript/bin/tsc"), "-p", app], app);
  lines.push("a TypeScript consumer typechecks against the installed declarations (module nodenext, skipLibCheck false)");
} finally {
  rmSync(dir, { recursive: true, force: true });
}
const md = `# shaida-sdk publishing rehearsal (nothing published)\n\nGenerated by \`pnpm --filter shaida-sdk pack-check\` (packages/sdk/scripts/pack-check.mjs) on ${new Date().toISOString()}. The temp project was removed afterwards.\n\n${lines.map((l) => `- ${l}`).join("\n")}\n`;
mkdirSync(join(REPO, "evidence/sdk"), { recursive: true });
writeFileSync(join(REPO, "evidence/sdk/pack.md"), md);
console.log(md);
process.exit(0);
