// The SDK against Aevum testnet 44005 itself (read-only: eth_call, eth_getLogs, block reads; nothing is sent), from
// the built dist/. Run 1's link for "Landlord Bola" and the bot's sample link; writes evidence/sdk/live-44005.md.
// A failed check writes evidence/sdk/live-44005-FAILED-<time>.md and exits 1.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { checkOnChain, decodeIncomeLink, RENT_CHECK, REVENUE_CREDIT, underwrite, verifyIncomeLink } from "../dist/index.js";

const REPO = fileURLToPath(new URL("../../../", import.meta.url));
const run1 = JSON.parse(readFileSync(`${REPO}web/src/app/example-links.json`, "utf8"))["44005"].link;
const botRun = JSON.parse(readFileSync(`${REPO}evidence/underwrite-live-44005/run.json`, "utf8"));
const bot = botRun.link;
// The live bot's recorded decisions for the same link: the SDK runs the same engine, so the ids must match.
const botId = (label) => botRun.decisions[label].decisionId.replace("…", "");
const edited = (link, f) => { const j = JSON.parse(Buffer.from(link.split("#")[1], "base64url")); f(j); return `/v#${Buffer.from(JSON.stringify(j)).toString("base64url")}`; };
const net = { network: "aevum-testnet" };
const rows = [];
let failed = 0;
const row = async (what, want, run) => {
  const t0 = Date.now();
  let got;
  try { got = await run(); } catch (e) { got = `threw ${e.name}: ${e.message}`; }
  const ok = got.startsWith(want);
  if (!ok) failed++;
  rows.push(`| ${what} | ${want} | ${got.replace(/\|/g, "\\|")} | ${Date.now() - t0} | ${ok ? "✓" : "✗"} |`);
};
const v = (r) => (r.status === "VALID" ? `VALID ${Number(r.threshold) / 1e6} tUSD8, ${r.count} payments, ${r.from.toISOString()} → ${r.to.toISOString()}, expires ${r.expiry.toISOString()}, block ${r.block}` : `${r.status} ${r.code}`);
const d = (r) => `${r.kind}${r.kind === "DECLINE" ? `(${r.reasons.map((x) => x.code).join(",")})` : r.kind === "INCONCLUSIVE" ? `(${r.error.code})` : ""} ${r.decisionId.slice(0, 16)}`;

const started = new Date().toISOString();
await row("decodeIncomeLink(run 1)", "ok", async () => { const r = decodeIncomeLink(run1); return r.ok ? `ok ${r.link.proofs.length} proof(s), threshold ${r.link.proofs[0].threshold}` : r.code; });
await row("verifyIncomeLink(run 1, Landlord Bola)", "VALID", async () => v(await verifyIncomeLink(run1, { ...net, readerName: "Landlord Bola" })));
await row("verifyIncomeLink(run 1, Tenant Chidi)", "INVALID WrongReader", async () => v(await verifyIncomeLink(run1, { ...net, readerName: "Tenant Chidi" })));
await row("verifyIncomeLink(run 1 with threshold 3 → 4 tUSD8)", "INVALID ProofInvalid", async () => v(await verifyIncomeLink(edited(run1, (j) => { j.proofs[0].publicSignals[2] = "4000000"; }), { ...net, readerName: "Landlord Bola" })));
await row("checkOnChain(run 1): IncomeVerifier.check", "ACCEPTED", async () => { const r = await checkOnChain(run1, net); return r.status === "ACCEPTED" ? `ACCEPTED ${r.proofs} proof(s) at block ${r.block}` : `${r.status} ${r.code}`; });
await row("checkOnChain(run 1 with threshold 3 → 4 tUSD8)", "REJECTED ProofInvalid", async () => { const r = await checkOnChain(edited(run1, (j) => { j.proofs[0].publicSignals[2] = "4000000"; }), net); return `${r.status} ${r.code ?? ""} proof ${r.proof ?? ""}`; });
await row("underwrite(bot sample link, RENT_CHECK): same decisionId as the live bot's", `APPROVE ${botId("rent-check@1")}`, async () => d(await underwrite(bot, RENT_CHECK, net)));
await row("underwrite(bot sample link, REVENUE_CREDIT): same decisionId as the live bot's", `DECLINE(BelowMinThreshold,TooFewPayments,PeriodTooShort) ${botId("revenue-credit@1")}`, async () => d(await underwrite(bot, REVENUE_CREDIT, net)));
await row("underwrite(run 1, RENT_CHECK): made out to Landlord Bola", "DECLINE(WrongReader)", async () => d(await underwrite(run1, RENT_CHECK, net)));
await row("verifyIncomeLink over an RPC that is down", "INCONCLUSIVE ChainUnreachable", async () => v(await verifyIncomeLink(run1, { ...net, readerName: "Landlord Bola", rpcUrl: "http://127.0.0.1:9", timeoutMs: 2000 })));

const md = `# shaida-sdk against Aevum testnet 44005\n\nGenerated by \`pnpm --filter shaida-sdk live\` (packages/sdk/scripts/live-44005.mjs) from the built dist/,
started ${started}, RPC https://rpc-test.qday.info (the bundled default). Read-only: eth_chainId, eth_blockNumber, eth_call (isKnownRoot,
nextIndex, IncomeVerifier.check with 400k gas), eth_getLogs over ≤ 1000 blocks, eth_getBlockByNumber. Nothing was sent. Personas are demo.

Result: ${failed ? `**FAILED** (${failed} row(s))` : "all rows as expected"}

| Call | Expected | Got | ms | |\n|---|---|---|---:|---|\n${rows.join("\n")}\n`;
mkdirSync(`${REPO}evidence/sdk`, { recursive: true });
const out = failed ? `${REPO}evidence/sdk/live-44005-FAILED-${started.replace(/[:.]/g, "-")}.md` : `${REPO}evidence/sdk/live-44005.md`;
writeFileSync(out, md);
console.log(md);
process.exit(failed ? 1 : 0);
