// Checks the published package (not the local tarball): npm install shaida-sdk@<version> from registry.npmjs.org
// into an empty temp project, confirm the lockfile resolved it from the registry with the integrity of the tarball
// that was packed, run examples/verify-node.mjs on 44005 (read-only), typecheck a consumer under nodenext.
// Writes evidence/sdk/npm-install.md. Usage: pnpm --filter shaida-sdk npm-check
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const PKG = fileURLToPath(new URL("..", import.meta.url));
const REPO = join(PKG, "../..");
const { name, version } = JSON.parse(readFileSync(join(PKG, "package.json"), "utf8"));
const PACKED_INTEGRITY = "sha512-3az4S9NuZV7Bgj6xkC9YaJowBM7zm3TsSEmAeJ8xDWBJBwSjWuuxBt1+yai3KZTwkOeqrEc17TcOFrtWiOCAtA==";
const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !/^npm_/i.test(k) && k !== "PNPM_SCRIPT_SRC_DIR"));
const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, env, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
const app = mkdtempSync(join(tmpdir(), "shaida-sdk-npm-"));
const lines = [];
try {
  writeFileSync(join(app, "package.json"), '{"name":"clean-integrator","private":true,"type":"module"}\n');
  run("npm", ["install", "--no-audit", "--no-fund", "--registry=https://registry.npmjs.org/", `${name}@${version}`], app);
  const locked = JSON.parse(readFileSync(join(app, "package-lock.json"), "utf8")).packages[`node_modules/${name}`];
  if (!locked.resolved.startsWith("https://registry.npmjs.org/")) throw new Error(`not from the registry: ${locked.resolved}`);
  if (locked.integrity !== PACKED_INTEGRITY) throw new Error(`integrity ${locked.integrity} is not the packed tarball's`);
  const count = Object.keys(JSON.parse(readFileSync(join(app, "package-lock.json"), "utf8")).packages).filter((k) => k).length;
  lines.push(`npm install ${name}@${version} (npm ${run("npm", ["-v"], app).trim()}, node ${process.version}): ${count} packages`);
  lines.push(`resolved ${locked.resolved}, integrity ${locked.integrity} (equal to the tarball packed at 134d704, evidence/sdk/pack.md)`);
  copyFileSync(join(REPO, "examples/verify-node.mjs"), join(app, "verify-node.mjs"));
  const link = JSON.parse(readFileSync(join(REPO, "web/src/app/example-links.json"), "utf8"))["44005"].link;
  lines.push(`examples/verify-node.mjs, run 1 on 44005, "Landlord Bola": ${run(process.execPath, ["verify-node.mjs", `https://shaida.onrender.com${link}`, "Landlord Bola"], app).trim()}`);
  writeFileSync(join(app, "consumer.ts"), `import { verifyIncomeLink, type Verification } from "${name}";\nconst v: Verification = await verifyIncomeLink("#x", { readerName: "a", network: "aevum-testnet" });\nif (v.status === "VALID") { const t: bigint = v.threshold; console.log(t); } else console.log(v.code);\n`);
  writeFileSync(join(app, "tsconfig.json"), '{"compilerOptions":{"module":"nodenext","moduleResolution":"nodenext","target":"es2022","strict":true,"noEmit":true,"skipLibCheck":false,"types":[]},"files":["consumer.ts"]}\n');
  run(process.execPath, [join(PKG, "node_modules/typescript/bin/tsc"), "-p", app], app);
  lines.push("a TypeScript consumer typechecks against the installed declarations (module nodenext, skipLibCheck false)");
} finally {
  rmSync(app, { recursive: true, force: true });
}
const md = `# ${name}@${version} installed from npm\n\nGenerated by \`pnpm --filter ${name} npm-check\` (packages/sdk/scripts/npm-check.mjs) on ${new Date().toISOString()}, in an empty temp project outside the repository (removed afterwards). https://www.npmjs.com/package/${name}\n\n${lines.map((l) => `- ${l}`).join("\n")}\n`;
writeFileSync(join(REPO, "evidence/sdk/npm-install.md"), md);
console.log(md);
process.exit(0);
