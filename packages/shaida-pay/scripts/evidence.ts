// Writes evidence/<slug>-fork.md (+ .json) from a run (acts-2-3 by default). Never hand-edited (BUILD_CONTRACT "Never fabricate").
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { cpus, platform } from "node:os";
import { join } from "node:path";
import { z } from "zod";
import type { Address } from "viem";
import { REPO } from "./node-env";

export interface ActRow { act: string; what: string; fn: string; hash: string; block: string; gasUsed: string }
export interface Deployment { pool: Address; ledger: Address; depositor: Address; registry: Address; memo: Address; incomeVerifier: Address; gitCommit: string; gitDirty: boolean; poolDeployBlock: number }

const addr = z.object({ address: z.string().regex(/^0x[0-9a-fA-F]{40}$/) }).passthrough();
const depSchema = z.object({
  chainId: z.literal(440050), gitCommit: z.string(), gitDirty: z.boolean(), poolDeployBlock: z.number(),
  contracts: z.object({ ShieldPoolPoseidon: addr, ShaidaLedger: addr, ShaidaDepositor: addr, PayerRegistry: addr, GloamPayMemo: addr, IncomeVerifier: addr }).passthrough(),
}).passthrough();

export function readDeployment(): Deployment {
  const path = join(REPO, "deployments/fork.json");
  if (!existsSync(path)) throw new Error("deployments/fork.json not found: run make deploy-fork");
  const d = depSchema.parse(JSON.parse(readFileSync(path, "utf8")));
  const a = (k: keyof typeof d.contracts) => (d.contracts[k] as { address: string }).address.toLowerCase() as Address;
  return { pool: a("ShieldPoolPoseidon"), ledger: a("ShaidaLedger"), depositor: a("ShaidaDepositor"), registry: a("PayerRegistry"), memo: a("GloamPayMemo"), incomeVerifier: a("IncomeVerifier"), gitCommit: d.gitCommit, gitDirty: d.gitDirty, poolDeployBlock: d.poolDeployBlock };
}

const git = (args: string[]) => execFileSync("git", args, { cwd: REPO, encoding: "utf8" }).trim();

export interface EvidenceKind { readonly slug: string; readonly title: string; readonly command: string; readonly personas: string }
const ACTS_2_3: EvidenceKind = { slug: "acts-2-3", title: "acts 2–3", command: "pnpm --filter @shaida/pay exit:acts-2-3", personas: "Acme Studio (demo) and Ada (demo)" };

export function writeEvidence(run: { rows: ActRow[]; rpc: string; base: string; dep?: Deployment; checks?: string[]; failure?: string; kind?: EvidenceKind; extra?: Record<string, unknown> }): void {
  const kind = run.kind ?? ACTS_2_3;
  const commit = git(["rev-parse", "HEAD"]);
  const dirty = git(["status", "--porcelain", "--", ".", ":!evidence"]) !== "";
  const at = new Date().toISOString();
  const lines = [
    `# Exit check, PRD §11 ${kind.title} (fork)${run.failure ? ": FAILED" : ""}`,
    "",
    `Generated by \`${kind.command}\`. Do not edit by hand. Personas are demo: ${kind.personas}.`,
    "",
    "| Field | Value |",
    "|---|---|",
    "| Class | fork (`make fork`: anvil --hardfork shanghai, chain 440050, real tUSD8 and Gloam final verifiers) |",
    `| App | ${run.base} (/api/index, /api/relay/*) · RPC ${run.rpc} |`,
    `| Commit | \`${commit}\`${dirty ? " (working tree dirty)" : ""} |`,
    `| Contracts deployed from | ${run.dep ? `\`${run.dep.gitCommit}\`${run.dep.gitDirty ? " (dirty)" : ""}, pool at block ${run.dep.poolDeployBlock}` : "—"} |`,
    `| Machine | ${platform()} ${cpus().length} CPUs, node ${process.version} |`,
    `| Date | ${at} |`,
    `| Result | ${run.failure ? `**FAILED**: ${run.failure}` : "passed"} |`,
    "",
    "| Act | What | Relayed function | Tx hash | Block | Gas used |",
    "|---|---|---|---|---:|---:|",
    ...run.rows.map((r) => `| ${r.act} | ${r.what} | ${r.fn} | \`${r.hash}\` | ${r.block} | ${r.gasUsed === "—" ? "—" : Number(r.gasUsed).toLocaleString("en-US")} |`),
    "",
    ...(run.checks ?? []).map((c) => `- ${c}`),
    "",
  ];
  const name = run.failure ? `${kind.slug}-fork-FAILED-${at.replace(/[:.]/g, "-")}` : `${kind.slug}-fork`;
  writeFileSync(join(REPO, "evidence", `${name}.md`), lines.join("\n"));
  writeFileSync(join(REPO, "evidence", `${name}.json`), JSON.stringify({ at, commit, dirty, ...run, kind }, (_k, v: unknown) => (typeof v === "bigint" ? v.toString() : v), 2) + "\n");
  console.log(`${run.failure ? "✗" : "✓"} evidence/${name}.md`);
}
